#!/usr/bin/env bash
# ============================================================
#  کبیر — اسکریپت به‌روزرسانی (لینوکس)
# ============================================================
#  به‌صورت خودکار:
#    ۱) آخرین نسخه را از گیت می‌گیرد (اگر پوشه کلون گیت باشد)
#    ۲) وابستگی‌ها را به‌روز می‌کند
#    ۳) از پایگاه‌داده پشتیبان می‌گیرد
#    ۴) مهاجرت پایگاه‌داده را بدون دست‌زدن به داده‌ها اعمال می‌کند
#    ۵) قیمت پروژه‌ها را با نرخ‌های جاری بازمحاسبه می‌کند
#
#  داده‌های شما خارج از پوشه‌ی برنامه نگهداری می‌شوند و با
#  به‌روزرسانی از بین نمی‌روند:
#    ~/.local/share/KabirCabinet
#
#  اجرا:  ./update.sh
# ============================================================
set -e
cd "$(dirname "$0")"

if command -v python3 >/dev/null 2>&1; then
  PY=python3
elif command -v python >/dev/null 2>&1; then
  PY=python
else
  echo "[ERROR] Python 3 not found. Install python3 (e.g. sudo apt install python3) and retry."
  exit 1
fi

exec "$PY" update.py "$@"
